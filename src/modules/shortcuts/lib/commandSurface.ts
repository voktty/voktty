export function commandSurfaceRule(id: string): CommandSurfaceRule {
  return declaredCommandSurfaceRule(id) ?? GLOBAL;
}

export function declaredCommandSurfaceRule(id: string): CommandSurfaceRule | undefined {
  if (id.startsWith("spaces.switch.") && id.length > "spaces.switch.".length) return GLOBAL;
  return Object.prototype.hasOwnProperty.call(COMMAND_RULES, id) ? COMMAND_RULES[id] : undefined;
}

export function commandSurfaceUnavailableReason(
  id: string,
  surface: Pick<ActiveSurface, "kind">,
): CommandSurfaceRule["unavailableReason"] {
  const rule = commandSurfaceRule(id);
  return rule.appliesTo.includes(surface.kind) ? null : rule.unavailableReason;
}
